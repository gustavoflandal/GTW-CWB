package muralha.digital.veiculo;

public class VeiculoDeCargaRelatorio {
    private String placa;
    private String data;
    private String pesagem;
    private String pbt;
    private String pbtc;
    private String numeroEixos;
    private String pesosEixos;
    private String distanciasEixos;
    private String equipamento;
    private String classificacao;
    
    public String getPlaca() { return placa; }
    public void setPlaca(String placa) { this.placa = placa; }
    
    public String getData() { return data; }
    public void setData(String data) { this.data = data; }
    
    public String getPesagem() { return pesagem; }
    public void setPesagem(String pesagem) { this.pesagem = pesagem; }
    
    public String getPbt() { return pbt; }
    public void setPbt(String pbt) { this.pbt = pbt; }
    
    public String getPbtc() { return pbtc; }
    public void setPbtc(String pbtc) { this.pbtc = pbtc; }
    
    public String getNumeroEixos() { return numeroEixos; }
    public void setNumeroEixos(String numeroEixos) { this.numeroEixos = numeroEixos; }
    
    public String getPesosEixos() { return pesosEixos; }
    public void setPesosEixos(String pesosEixos) { this.pesosEixos = pesosEixos; }
    
    public String getDistanciasEixos() { return distanciasEixos; }
    public void setDistanciasEixos(String distanciasEixos) { this.distanciasEixos = distanciasEixos; }
    
    public String getEquipamento() { return equipamento; }
    public void setEquipamento(String equipamento) { this.equipamento = equipamento; }
    
    public String getClassificacao() { return classificacao; }
    public void setClassificacao(String classificacao) { this.classificacao = classificacao; }
}